// The token radar's model, radar-2: one snapshot of the protocol universe in,
// one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a
// ceiling) and every protocol below the floor that passes the watchlist's own
// rule: it records no token, and it is not a wrapped, staked or bridged product
// of a protocol whose token already trades. A protocol is pre-token when its
// index entry records no token (no market cap, no CoinGecko id, no symbol);
// the snapshot's live-token protocols are kept apart and shown as the market's
// own values, never mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures, and it is
// calibrated from the snapshot itself on every run, so the same program finds
// future airdrops early on a fresh snapshot without a hand-kept list:
//
//   category multiple = the median market-cap / TVL of the live protocols in
//       the same category (at least 3 live comparables, else the market median
//       over all live protocols), clamped to [0.08, 0.55]
//   base       = tvl_usd x category multiple
//   growth     = clamp(change_7d, -50, 100) per cent
//   growthMult = 1 + (growth / 100) x 0.75
//   maturity   = 0.65 + min(age_days, 1095) / 1095 x 0.5
//                (age_days unknown: 365, so 0.82)
//   chainMult  = 1 + 0.03 x min(chains - 1, 10)
//   implied    = max(1, round(base x growthMult x maturity x chainMult))
//
// The category multiple is the market's own answer to "what is a dollar of
// TVL in this kind of protocol worth as a token": a live DEX's token trades
// near a third of its TVL, a live lender's near a seventh. A protocol's
// growth says whether capital is arriving, its age with no token says how
// seasoned it is, and its chain count says how wide its reach is. No
// protocol name is ever special-cased: the same function scores every row.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

